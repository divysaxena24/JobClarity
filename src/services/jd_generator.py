def call_openai_generator(params: Mapping[str, str], api_key: str, model: str = "gpt-4o-mini") -> str:
    """
    Call OpenAI API to generate a realistic synthetic job description.
    """
    prompt = (
        f"Generate a realistic, professional, detailed job description for a '{params['job_role']}' position.\n"
        f"Requirements:\n"
        f"- Experience Level: {params['experience_level']}\n"
        f"- Required Skills: {params['skills']}\n"
        f"- Location: {params['location']}\n"
        f"- Company: {params['company_name']}\n"
        f"- Compensation: {params['salary_range']}\n\n"
        f"Format with sections: Company Overview, Role Summary, Responsibilities, Requirements, and Benefits. "
        f"Do not include preamble, conversational remarks, or markdown code fences; return only the job posting text."
    )

    url = "https://api.openai.com/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": model,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are a professional HR and recruitment specialist. "
                    "You write clear, detailed, and realistic job descriptions."
                ),
            },
            {"role": "user", "content": prompt},
        ],
        "temperature": 0.7,
        "max_tokens": 1000,
    }

    with httpx.Client(timeout=15.0) as client:
        resp = client.post(url, headers=headers, json=payload)
        resp.raise_for_status()
        data = resp.json()
        return data["choices"][0]["message"]["content"].strip()


def call_gemini_generator(params: Mapping[str, str], api_key: str) -> str:
    """
    Call Google Gemini API to generate a realistic synthetic job description.
    """
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    prompt = (
        f"Generate a realistic, professional, detailed job description for a '{params['job_role']}' position.\n"
        f"Experience Level: {params['experience_level']}\n"
        f"Required Skills: {params['skills']}\n"
        f"Location: {params['location']}\n"
        f"Company: {params['company_name']}\n"
        f"Compensation: {params['salary_range']}\n\n"
        f"Format with sections: Company Overview, Role Summary, Responsibilities, Requirements, and Benefits. "
        f"Return only the text of the job description without code fences or preamble."
    )

    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"temperature": 0.7, "maxOutputTokens": 1000},
    }

    with httpx.Client(timeout=15.0) as client:
        resp = client.post(url, json=payload)
        resp.raise_for_status()
        data = resp.json()
        return data["candidates"][0]["content"]["parts"][0]["text"].strip()


def generate_job_description(
    job_role: str,
    skills: str | list[str],
    experience_level: str,
    location: str,
    company_name: str | None = None,
    salary_range: str | None = None,
    preferred_provider: str | None = None,
) -> dict[str, Any]:
    """
    Orchestrate synthetic job description generation:
      1. Validates input parameters.
      2. Attempts configured AI provider (OpenAI / Gemini) if credentials exist in environment.
      3. Gracefully falls back to deterministic template generation if unconfigured or on failure.
      4. Attaches disclaimer and metadata.
    """
    params = validate_jd_inputs(
        job_role=job_role,
        skills=skills,
        experience_level=experience_level,
        location=location,
        company_name=company_name,
        salary_range=salary_range,
    )

    openai_key = os.environ.get("OPENAI_API_KEY")
    gemini_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")

    provider_used = "synthetic_template"
    jd_text = ""

    # Attempt OpenAI if configured
    if (preferred_provider == "openai" or not preferred_provider) and openai_key:
        try:
            jd_text = call_openai_generator(params, api_key=openai_key)
            provider_used = "openai"
        except Exception as exc:
            logger.warning("OpenAI JD generation call failed, falling back: %s", str(exc))

    # Attempt Gemini if configured and OpenAI wasn't used
    if not jd_text and (preferred_provider == "gemini" or not preferred_provider) and gemini_key:
        try:
            jd_text = call_gemini_generator(params, api_key=gemini_key)
            provider_used = "gemini"
        except Exception as exc:
            logger.warning("Gemini JD generation call failed, falling back: %s", str(exc))

    # Safe fallback
    if not jd_text:
        jd_text = generate_synthetic_template_jd(params)
        provider_used = "synthetic_template"

    return {
        "generated_job_description": jd_text,
        "is_ai_generated": True,
        "provider": provider_used,
        "disclaimer": DISCLAIMER_TEXT,
        "input_parameters": {
            "job_role": params["job_role"],
            "skills": params["skills"],
            "experience_level": params["experience_level"],
            "location": params["location"],
            "company_name": params["company_name"],
            "salary_range": params["salary_range"],
        },
    }
