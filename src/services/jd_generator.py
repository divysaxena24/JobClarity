"""
Job Description Generator Service for JobClarity (Day 7).

Generates synthetic, editable job descriptions from structured inputs:
  - Required inputs: job_role, skills, experience_level, location.
  - Optional inputs: company_name, salary_range, job_type.
  - Integrates with external LLM providers (OpenAI / Gemini) if API keys are configured.
  - Never hardcodes or invents credentials.
  - Gracefully falls back to high-quality template-based synthesis if provider is unconfigured or fails.
  - Clearly labels all generated content as AI-generated.
  - Includes trust & safety disclaimer that predictions are risk estimates, not proof of fraud.
"""

from __future__ import annotations

import logging
import os
import re
from typing import Any, Mapping

import httpx

logger = logging.getLogger(__name__)

DISCLAIMER_TEXT = (
    "Notice: This job description was synthetically generated for demonstration and evaluation. "
    "Predictions generated by JobClarity are statistical risk estimates based on language patterns, "
    "not conclusive proof of fraud or employer verification."
)


def validate_jd_inputs(
    job_role: str,
    skills: str | list[str],
    experience_level: str,
    location: str,
    company_name: str | None = None,
    salary_range: str | None = None,
) -> dict[str, str]:
    """
    Validate and normalize job description generation inputs.
    Raises ValueError on invalid or missing required parameters.
    """
    if not isinstance(job_role, str) or not job_role.strip():
        raise ValueError("job_role is required and must be a non-empty string.")
    if len(job_role.strip()) > 120:
        raise ValueError("job_role must not exceed 120 characters.")

    if isinstance(skills, list):
        clean_skills = [str(s).strip() for s in skills if str(s).strip()]
        if not clean_skills:
            raise ValueError("skills list cannot be empty.")
        skills_str = ", ".join(clean_skills)
    elif isinstance(skills, str):
        skills_str = skills.strip()
        if not skills_str:
            raise ValueError("skills must be a non-empty string.")
    else:
        raise ValueError("skills must be a string or list of strings.")

    if len(skills_str) > 500:
        raise ValueError("skills must not exceed 500 characters.")

    if not isinstance(experience_level, str) or not experience_level.strip():
        raise ValueError("experience_level is required and must be a non-empty string.")

    if not isinstance(location, str) or not location.strip():
        raise ValueError("location is required and must be a non-empty string.")

    norm_company = company_name.strip() if isinstance(company_name, str) and company_name.strip() else "Acme Innovations"
    norm_salary = salary_range.strip() if isinstance(salary_range, str) and salary_range.strip() else None

    return {
        "job_role": job_role.strip(),
        "skills": skills_str,
        "experience_level": experience_level.strip(),
        "location": location.strip(),
        "company_name": norm_company,
        "salary_range": norm_salary or "Competitive compensation based on experience",
    }


